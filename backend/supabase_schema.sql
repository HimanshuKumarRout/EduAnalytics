-- ==============================================================================
-- Supabase PostgreSQL Schema for EduAnalytics - Student Performance Analysis
-- Run this in the Supabase Dashboard -> SQL Editor (or via psql)
-- ==============================================================================

-- 1. Create Students Table
CREATE TABLE IF NOT EXISTS public.students_student (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    gender VARCHAR(10) NOT NULL,
    date_of_birth DATE NULL,
    class_name VARCHAR(20) NOT NULL,
    section VARCHAR(5) DEFAULT '',
    roll_number INTEGER NULL,
    parent_name VARCHAR(100) DEFAULT '',
    contact VARCHAR(15) DEFAULT '',
    address TEXT DEFAULT '',
    photo VARCHAR(100) NULL,
    enrolled_on DATE DEFAULT CURRENT_DATE,
    is_active BOOLEAN DEFAULT TRUE
);

-- 2. Create Subjects Table
CREATE TABLE IF NOT EXISTS public.students_subject (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(20) NOT NULL UNIQUE,
    max_marks INTEGER DEFAULT 100,
    class_name VARCHAR(20) NOT NULL,
    teacher VARCHAR(100) DEFAULT ''
);

-- 3. Create Exam Results Table
CREATE TABLE IF NOT EXISTS public.students_examresult (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students_student(id) ON DELETE CASCADE,
    subject_id BIGINT NOT NULL REFERENCES public.students_subject(id) ON DELETE CASCADE,
    exam_type VARCHAR(20) NOT NULL,
    exam_date DATE NOT NULL,
    marks_obtained DOUBLE PRECISION NOT NULL,
    max_marks DOUBLE PRECISION DEFAULT 100,
    grade VARCHAR(3) DEFAULT '',
    remarks TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT students_examresult_unique_exam UNIQUE (student_id, subject_id, exam_type)
);

-- 4. Create Attendance Table
CREATE TABLE IF NOT EXISTS public.students_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students_student(id) ON DELETE CASCADE,
    subject_id BIGINT NULL REFERENCES public.students_subject(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    is_present BOOLEAN DEFAULT TRUE,
    remarks VARCHAR(200) DEFAULT '',
    CONSTRAINT students_attendance_unique_entry UNIQUE (student_id, date, subject_id)
);

-- 5. Create Indexes for High Performance Queries
CREATE INDEX IF NOT EXISTS idx_student_class ON public.students_student(class_name);
CREATE INDEX IF NOT EXISTS idx_student_active ON public.students_student(is_active);
CREATE INDEX IF NOT EXISTS idx_examresult_student ON public.students_examresult(student_id);
CREATE INDEX IF NOT EXISTS idx_examresult_subject ON public.students_examresult(subject_id);
CREATE INDEX IF NOT EXISTS idx_examresult_date ON public.students_examresult(exam_date);

